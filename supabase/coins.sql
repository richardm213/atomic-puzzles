create or replace function public.give_coins(
  p_sender_username text,
  p_recipient_username text,
  p_amount integer,
  p_message text default null
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  sender_name text := lower(btrim(coalesce(p_sender_username, '')));
  recipient_name text := lower(btrim(coalesce(p_recipient_username, '')));
  clean_message text := nullif(btrim(coalesce(p_message, '')), '');
  transfer public.coin_transfers%rowtype;
  current_balance integer;
  claimed_today boolean;
begin
  if sender_name = '' or recipient_name = '' or sender_name = recipient_name then
    raise exception 'Invalid coin recipient';
  end if;
  if p_amount is null or p_amount < 1 or p_amount > 100000 then
    raise exception 'Coin amount must be between 1 and 100000';
  end if;
  if length(coalesce(clean_message, '')) > 280 then
    raise exception 'Coin message is too long';
  end if;
  if not exists (select 1 from public.users where lower(btrim(username)) = recipient_name) then
    raise exception 'Recipient must have an Atomic Puzzles account';
  end if;

  insert into public.coin_transfers (sender_username, recipient_username, amount, message)
  values (sender_name, recipient_name, p_amount, clean_message)
  returning * into transfer;

  current_balance := public.apply_coin_transaction(
    sender_name, -p_amount, 'coin_transfer', 'transfer:' || transfer.id || ':sent',
    jsonb_build_object('transferId', transfer.id, 'recipient', recipient_name), transfer.created_at
  );
  perform public.apply_coin_transaction(
    recipient_name, p_amount, 'coin_transfer', 'transfer:' || transfer.id || ':received',
    jsonb_build_object('transferId', transfer.id, 'sender', sender_name), transfer.created_at
  );

  insert into public.notifications (
    recipient_username, actor_username, notification_type, puzzle_id, comment_id,
    coin_amount, coin_message, coin_transfer_id
  ) values (
    recipient_name, sender_name, 'coin_gift', null, null,
    p_amount, clean_message, transfer.id
  );

  select exists (
    select 1 from public.coin_transactions
    where source_key = 'daily:' || sender_name || ':' || current_date::text
  ) into claimed_today;

  return jsonb_build_object(
    'balance', current_balance,
    'dailyClaimAvailable', not claimed_today,
    'transferId', transfer.id,
    'recipientUsername', recipient_name,
    'amount', p_amount
  );
end;
$$;

create or replace function public.request_coins(
  p_requester_username text,
  p_recipient_username text,
  p_amount integer,
  p_message text default null
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  requester_name text := lower(btrim(coalesce(p_requester_username, '')));
  recipient_name text := lower(btrim(coalesce(p_recipient_username, '')));
  clean_message text := nullif(btrim(coalesce(p_message, '')), '');
  coin_request public.coin_requests%rowtype;
begin
  if requester_name = '' or recipient_name = '' or requester_name = recipient_name then
    raise exception 'Invalid coin request recipient';
  end if;
  if p_amount is null or p_amount < 1 or p_amount > 100000 then
    raise exception 'Coin amount must be between 1 and 100000';
  end if;
  if length(coalesce(clean_message, '')) > 280 then
    raise exception 'Coin message is too long';
  end if;
  if not exists (select 1 from public.users where lower(btrim(username)) = recipient_name) then
    raise exception 'Recipient must have an Atomic Puzzles account';
  end if;
  if (
    select count(*) from public.coin_requests
    where requester_username = requester_name
      and recipient_username = recipient_name
      and created_at > now() - interval '1 hour'
  ) >= 5 then
    raise exception 'Too many coin requests';
  end if;

  insert into public.coin_requests (requester_username, recipient_username, amount, message)
  values (requester_name, recipient_name, p_amount, clean_message)
  returning * into coin_request;

  insert into public.notifications (
    recipient_username, actor_username, notification_type, puzzle_id, comment_id,
    coin_amount, coin_message, coin_request_id
  ) values (
    recipient_name, requester_name, 'coin_request', null, null,
    p_amount, clean_message, coin_request.id
  );

  return public.get_coin_summary(requester_name) || jsonb_build_object(
    'requestId', coin_request.id,
    'recipientUsername', recipient_name,
    'amount', p_amount,
    'status', coin_request.status
  );
end;
$$;

