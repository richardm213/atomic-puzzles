-- Atomic Coins: append-only rewards, daily claims, and shop redemptions.
-- Backfill begins at 2026-09-20 00:00 UTC and is safe to rerun.
begin;

create table if not exists public.coin_accounts (
  username text primary key check (username = lower(btrim(username)) and length(username) > 0),
  balance integer not null default 0 check (balance >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.coin_transactions (
  id bigint generated by default as identity primary key,
  username text not null check (username = lower(btrim(username)) and length(username) > 0),
  amount integer not null check (amount <> 0),
  reason text not null check (reason in ('puzzle_created', 'puzzle_correct', 'puzzle_attempted', 'daily_bonus', 'shop_redemption')),
  source_key text not null unique,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists coin_transactions_username_created_idx
  on public.coin_transactions (username, created_at desc, id desc);

create table if not exists public.shop_redemptions (
  id bigint generated by default as identity primary key,
  username text not null check (username = lower(btrim(username)) and length(username) > 0),
  item_key text not null check (item_key in ('discord_nitro_month', 'discord_nitro_year', 'flowers_500', 'lichess_patron_month', 'next_prize_tournament_format', 'atomicdb_analysis_12h')),
  cost integer not null default 500 check (
    (item_key = 'atomicdb_analysis_12h' and cost = 200)
    or cost = case
      when item_key = 'discord_nitro_month' then 400
      when item_key = 'discord_nitro_year' then 4000
      when item_key = 'lichess_patron_month' then 600
      when item_key = 'next_prize_tournament_format' then 1000
      else 500
    end
  ),
  status text not null default 'pending' check (status in ('pending', 'fulfilled', 'cancelled')),
  created_at timestamptz not null default now(),
  fulfilled_at timestamptz,
  fulfilled_by text,
  request_details jsonb not null default '{}'::jsonb
);

create index if not exists shop_redemptions_status_created_idx
  on public.shop_redemptions (status, created_at desc);

revoke all on table public.coin_accounts, public.coin_transactions, public.shop_redemptions
  from public, anon, authenticated;
revoke usage, select on sequence public.coin_transactions_id_seq, public.shop_redemptions_id_seq
  from public, anon, authenticated;

create or replace function public.apply_coin_transaction(
  p_username text,
  p_amount integer,
  p_reason text,
  p_source_key text,
  p_metadata jsonb default '{}'::jsonb,
  p_created_at timestamptz default now()
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_username text := lower(btrim(coalesce(p_username, '')));
  inserted_id bigint;
  next_balance integer;
begin
  if normalized_username = '' or p_amount = 0 or nullif(btrim(p_source_key), '') is null then
    raise exception 'Invalid coin transaction';
  end if;

  insert into public.coin_accounts (username) values (normalized_username)
  on conflict (username) do nothing;

  perform 1 from public.coin_accounts where username = normalized_username for update;

  insert into public.coin_transactions (username, amount, reason, source_key, metadata, created_at)
  values (normalized_username, p_amount, p_reason, btrim(p_source_key), coalesce(p_metadata, '{}'::jsonb), p_created_at)
  on conflict (source_key) do nothing
  returning id into inserted_id;

  if inserted_id is not null then
    update public.coin_accounts
    set balance = balance + p_amount, updated_at = now()
    where username = normalized_username and balance + p_amount >= 0
    returning balance into next_balance;
    if next_balance is null then raise exception 'Not enough coins'; end if;
  end if;

  select balance into next_balance from public.coin_accounts where username = normalized_username;
  return next_balance;
end;
$$;

revoke all on function public.apply_coin_transaction(text, integer, text, text, jsonb, timestamptz)
  from public, anon, authenticated;

create or replace function public.award_coins_for_puzzle_attempt()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  reward integer;
  puzzle_author text;
  puzzle_created_at timestamptz;
begin
  if not new.puzzle_correct then
    return new;
  end if;

  select lower(btrim(puzzle.author)), puzzle.created_at
  into puzzle_author, puzzle_created_at
  from public.puzzles puzzle
  where puzzle.id::text = new.puzzle_id;

  if puzzle_author = lower(btrim(new.username))
    and new.first_attempt_at >= puzzle_created_at
    and new.first_attempt_at < puzzle_created_at + interval '3 days' then
    return new;
  end if;

  select case coalesce(rating.human_level, rating.computed_level, 3)
    when 1 then 2
    when 2 then 2
    when 4 then 5
    when 5 then 10
    else 3
  end
  into reward
  from (select 1) fallback
  left join public.puzzle_ratings rating on rating.puzzle_id = new.puzzle_id::bigint;

  perform public.apply_coin_transaction(
    new.username,
    reward,
    'puzzle_correct',
    'attempt:' || lower(btrim(new.username)) || ':' || new.puzzle_id,
    jsonb_build_object('puzzleId', new.puzzle_id, 'correct', true, 'reward', reward),
    new.first_attempt_at
  );
  return new;
end;
$$;

drop trigger if exists award_coins_after_puzzle_attempt on public.puzzle_progress;
create trigger award_coins_after_puzzle_attempt
  after insert on public.puzzle_progress
  for each row execute function public.award_coins_for_puzzle_attempt();

create or replace function public.award_coins_for_created_puzzle()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if nullif(btrim(coalesce(new.author, '')), '') is not null then
    perform public.apply_coin_transaction(
      new.author, 10, 'puzzle_created', 'puzzle:' || new.id,
      jsonb_build_object('puzzleId', new.id), now()
    );
  end if;
  return new;
end;
$$;

drop trigger if exists award_coins_after_puzzle_created on public.puzzles;
create trigger award_coins_after_puzzle_created
  after insert on public.puzzles
  for each row execute function public.award_coins_for_created_puzzle();

create or replace function public.get_coin_summary(p_username text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  normalized_username text := lower(btrim(coalesce(p_username, '')));
  current_balance integer;
  claimed_today boolean;
begin
  insert into public.coin_accounts (username) values (normalized_username)
  on conflict (username) do nothing;
  select balance into current_balance from public.coin_accounts where username = normalized_username;
  select exists (
    select 1 from public.coin_transactions
    where source_key = 'daily:' || normalized_username || ':' || current_date::text
  ) into claimed_today;
  return jsonb_build_object('balance', current_balance, 'dailyClaimAvailable', not claimed_today);
end;
$$;

create or replace function public.claim_daily_coins(p_username text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  normalized_username text := lower(btrim(coalesce(p_username, '')));
  source text := 'daily:' || normalized_username || ':' || current_date::text;
  current_balance integer;
begin
  if exists (select 1 from public.coin_transactions where source_key = source) then
    raise exception 'Daily bonus already claimed';
  end if;
  current_balance := public.apply_coin_transaction(
    normalized_username, 5, 'daily_bonus', source,
    jsonb_build_object('date', current_date), now()
  );
  return jsonb_build_object('balance', current_balance, 'dailyClaimAvailable', false, 'awarded', 5);
end;
$$;

