-- Keep puzzle_set_id populated while the application still writes the
-- compatibility metadata fields on public.puzzles.
create or replace function public.assign_puzzle_set_id()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  normalized_players text[];
begin
  new.event_name := btrim(coalesce(new.event_name, ''));
  new.event_date := btrim(coalesce(new.event_date, ''));
  normalized_players := public.normalize_puzzle_set_players(new.players);
  new.players := normalized_players;

  if new.event_name = '' then
    new.puzzle_set_id := null;
    return new;
  end if;

  insert into public.puzzle_sets (event_name, event_date, players)
  values (new.event_name, new.event_date, normalized_players)
  on conflict do nothing;

  select id
  into new.puzzle_set_id
  from public.puzzle_sets
  where lower(btrim(event_name)) = lower(new.event_name)
    and event_date = new.event_date
    and public.normalize_puzzle_set_players(players) = normalized_players
  limit 1;

  return new;
end;
$$;

