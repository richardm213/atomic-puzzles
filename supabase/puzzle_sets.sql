-- Insert one canonical set for every distinct structured metadata combination.
insert into public.puzzle_sets (event_name, event_date, players)
select distinct on (
  lower(btrim(event_name)),
  event_date,
  public.normalize_puzzle_set_players(players)
)
  btrim(event_name),
  event_date,
  public.normalize_puzzle_set_players(players)
from public.puzzles
where btrim(coalesce(event_name, '')) <> ''
order by
  lower(btrim(event_name)),
  event_date,
  public.normalize_puzzle_set_players(players),
  id
on conflict do nothing;

-- Link every existing puzzle to its canonical set.
update public.puzzles p
set puzzle_set_id = puzzle_set.id
from public.puzzle_sets puzzle_set
where btrim(coalesce(p.event_name, '')) <> ''
  and lower(btrim(p.event_name)) = lower(btrim(puzzle_set.event_name))
  and p.event_date = puzzle_set.event_date
  and public.normalize_puzzle_set_players(p.players) =
      public.normalize_puzzle_set_players(puzzle_set.players)
  and p.puzzle_set_id is distinct from puzzle_set.id;

