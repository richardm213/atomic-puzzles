-- Keep binary-market exposure as one net position per user and market.
-- A Yes + No pair is a complete set, so closing the pair returns one coin.
begin;

create table if not exists public.prediction_position_nettings (
  id bigint generated by default as identity primary key,
  market_id text not null references public.prediction_markets(id),
  username text not null,
  quantity numeric(18, 6) not null check (quantity > 0),
  created_at timestamptz not null default now()
);

create index if not exists prediction_position_nettings_user_idx
  on public.prediction_position_nettings (username, market_id, created_at desc);

revoke all on table public.prediction_position_nettings from public, anon, authenticated;
alter table public.prediction_position_nettings enable row level security;

create or replace function public.net_prediction_position()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  opposite_outcome text := case when new.outcome = 'yes' then 'no' else 'yes' end;
  opposite_quantity numeric(18, 6);
  net_quantity numeric(18, 6);
  netting_id bigint;
begin
  if pg_trigger_depth() > 1 or new.quantity <= 0 or new.username = 'prediction_admin' then
    return null;
  end if;

  select quantity into opposite_quantity
  from public.prediction_positions
  where market_id = new.market_id
    and username = new.username
    and outcome = opposite_outcome
  for update;

  if coalesce(opposite_quantity, 0) <= 0 then return null; end if;

  -- Opposing exposure supersedes resting sell orders on the position being closed.
  update public.prediction_orders
  set remaining_quantity = 0,
      status = 'cancelled',
      updated_at = now()
  where market_id = new.market_id
    and username = new.username
    and outcome in (new.outcome, opposite_outcome)
    and side = 'sell'
    and status in ('open', 'partial')
    and remaining_quantity > 0;

  update public.prediction_positions
  set reserved_quantity = 0,
      updated_at = now()
  where market_id = new.market_id
    and username = new.username
    and outcome in (new.outcome, opposite_outcome);

  net_quantity := least(new.quantity, opposite_quantity);

  insert into public.prediction_position_nettings (market_id, username, quantity)
  values (new.market_id, new.username, net_quantity)
  returning id into netting_id;

  update public.prediction_positions
  set quantity = quantity - net_quantity,
      updated_at = now()
  where market_id = new.market_id
    and username = new.username
    and outcome in (new.outcome, opposite_outcome);

  perform public.apply_coin_transaction(
    new.username,
    net_quantity,
    'prediction_trade_credit',
    'prediction-position-net:' || netting_id,
    jsonb_build_object(
      'marketId', new.market_id,
      'nettingId', netting_id,
      'quantity', net_quantity,
      'reason', 'opposing-position-net'
    )
  );

  return null;
end;
$$;

revoke all on function public.net_prediction_position() from public, anon, authenticated;

drop trigger if exists prediction_positions_net_opposing on public.prediction_positions;
create trigger prediction_positions_net_opposing
after insert or update of quantity on public.prediction_positions
for each row
execute function public.net_prediction_position();

-- Normalize positions created before this invariant existed. The trigger also cancels any
-- resting sell order whose reserved contracts are consumed by the netting.
do $$
declare
  position_pair record;
begin
  for position_pair in
    select market_id, username
    from public.prediction_positions
    where quantity > 0
      and username <> 'prediction_admin'
    group by market_id, username
    having count(*) filter (where quantity > 0) > 1
  loop
    update public.prediction_positions
    set quantity = quantity
    where market_id = position_pair.market_id
      and username = position_pair.username
      and outcome = 'yes';
  end loop;
end;
$$;

commit;
