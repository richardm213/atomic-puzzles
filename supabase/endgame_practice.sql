-- Best endgame-practice time per player and independently randomized pawn category.
create table if not exists public.endgame_practice_bests (
  id bigint generated by default as identity primary key,
  player_key text not null,
  player_name text not null,
  mode text not null check (mode in (
    'pawn-duel',
    'blockade',
    'two-queens',
    'rook-vs-pawn',
    'rook-bishop-vs-king',
    'rook-pawn-vs-king'
  )),
  category text not null,
  duration_ms integer not null check (duration_ms between 100 and 3600000),
  completed_at timestamptz not null default now(),
  unique (player_key, mode, category),
  check (
    (mode in ('pawn-duel', 'blockade') and
      category ~ '^(rook|knight|regular)-file:rank-(3|regular|7)$') or
    (mode not in ('pawn-duel', 'blockade') and category = 'no-pawn')
  )
);

-- Keep an existing installation in sync when new practice modes are added.
alter table public.endgame_practice_bests
  drop constraint if exists endgame_practice_bests_mode_check;
alter table public.endgame_practice_bests
  add constraint endgame_practice_bests_mode_check check (mode in (
    'pawn-duel',
    'blockade',
    'two-queens',
    'rook-vs-pawn',
    'rook-bishop-vs-king',
    'rook-pawn-vs-king'
  ));

alter table public.endgame_practice_bests
  drop constraint if exists endgame_practice_bests_check;
alter table public.endgame_practice_bests
  add constraint endgame_practice_bests_check check (
    (mode in ('pawn-duel', 'blockade') and
      category ~ '^(rook|knight|regular)-file:rank-(3|regular|7)$') or
    (mode not in ('pawn-duel', 'blockade') and category = 'no-pawn')
  );

alter table public.endgame_practice_bests enable row level security;
revoke all on public.endgame_practice_bests from anon, authenticated;

create or replace function public.record_endgame_practice_best(
  p_player_key text,
  p_player_name text,
  p_mode text,
  p_category text,
  p_duration_ms integer
) returns public.endgame_practice_bests
language plpgsql
security definer
set search_path = public
as $$
declare result public.endgame_practice_bests;
begin
  insert into public.endgame_practice_bests
    (player_key, player_name, mode, category, duration_ms, completed_at)
  values
    (p_player_key, p_player_name, p_mode, p_category, p_duration_ms, now())
  on conflict (player_key, mode, category) do update
  set player_name = excluded.player_name,
      duration_ms = excluded.duration_ms,
      completed_at = excluded.completed_at
  where excluded.duration_ms < endgame_practice_bests.duration_ms
  returning * into result;

  if result.id is null then
    select * into result from public.endgame_practice_bests
    where player_key = p_player_key and mode = p_mode and category = p_category;
  end if;
  return result;
end;
$$;

revoke all on function public.record_endgame_practice_best(text, text, text, text, integer)
  from public, anon, authenticated;
grant execute on function public.record_endgame_practice_best(text, text, text, text, integer)
  to service_role;
