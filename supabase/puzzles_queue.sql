create or replace function public.enqueue_puzzle_submission(
  p_fen text,
  p_solution text,
  p_event text,
  p_event_name text,
  p_event_date text,
  p_players text[],
  p_white_player text,
  p_black_player text,
  p_explanation text,
  p_opa_style boolean,
  p_author text,
  p_tags text[],
  p_submitted_by text,
  p_allow_different_start_move boolean default false
)
returns public.puzzles_queue
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_username text := lower(btrim(coalesce(p_submitted_by, '')));
  normalized_fen text := btrim(coalesce(p_fen, ''));
  normalized_solution text := regexp_replace(
    btrim(coalesce(p_solution, '')),
    '[[:space:]]+',
    ' ',
    'g'
  );
  queued public.puzzles_queue%rowtype;
begin
  if normalized_username = '' then
    raise exception 'A verified username is required';
  end if;

  if normalized_fen = '' then
    raise exception 'A FEN is required';
  end if;

  if normalized_solution = '' then
    raise exception 'A solution is required';
  end if;


  insert into public.puzzles_queue (
    fen,
    solution,
    event,
    event_name,
    event_date,
    players,
    white_player,
    black_player,
    explanation,
    opa_style,
    author,
    tags,
    submitted_by
  )
  values (
    normalized_fen,
    normalized_solution,
    btrim(coalesce(p_event, '')),
    btrim(coalesce(p_event_name, '')),
    btrim(coalesce(p_event_date, '')),
    coalesce(p_players, '{}'::text[]),
    btrim(coalesce(p_white_player, '')),
    btrim(coalesce(p_black_player, '')),
    btrim(coalesce(p_explanation, '')),
    coalesce(p_opa_style, false),
    case
      when normalized_username = 'seaside_tiramisu'
        then coalesce(nullif(btrim(p_author), ''), normalized_username)
      else normalized_username
    end,
    coalesce(p_tags, '{}'::text[]),
    normalized_username
  )
  returning * into queued;

  return queued;
end;
$$;

-- Board-created puzzles keep their lead-in even when publication requires review.
create or replace function public.enqueue_puzzle_with_position_history(
  p_puzzle jsonb,
  p_submitted_by text,
  p_allow_different_start_move boolean default false
)
returns public.puzzles_queue
language plpgsql
security definer
set search_path = public
as $$
declare
  queued public.puzzles_queue%rowtype;
begin
  queued := public.enqueue_puzzle_submission(
    p_puzzle->>'fen', p_puzzle->>'solution', p_puzzle->>'event',
    p_puzzle->>'eventName', p_puzzle->>'eventDate',
    array(select jsonb_array_elements_text(p_puzzle->'players')),
    p_puzzle->>'whitePlayer', p_puzzle->>'blackPlayer', p_puzzle->>'explanation',
    coalesce((p_puzzle->>'opaStyle')::boolean, false), p_puzzle->>'author',
    array(select jsonb_array_elements_text(p_puzzle->'tags')),
    p_submitted_by, p_allow_different_start_move
  );

  update public.puzzles_queue
  set position_moves = p_puzzle->'positionMoves',
      game_initial_fen = p_puzzle->>'gameInitialFen'
  where id = queued.id
  returning * into queued;

  return queued;
end;
$$;

