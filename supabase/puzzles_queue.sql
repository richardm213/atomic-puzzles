-- Publishes a complete approved-creator batch atomically. The table lock keeps
-- ID allocation contiguous across concurrent creators.
drop function if exists public.publish_approved_puzzle_batch(jsonb, text);

create or replace function public.publish_approved_puzzle_batch(
  p_puzzles jsonb,
  p_submitted_by text,
  p_allow_different_start_move boolean default false
)
returns bigint[]
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_username text := lower(btrim(coalesce(p_submitted_by, '')));
  item jsonb;
  normalized_fen text;
  normalized_solution text;
  normalized_author text;
  next_puzzle_id bigint;
  puzzle_ids bigint[] := array[]::bigint[];
  puzzle_id_sequence text;
begin
  if normalized_username not in ('seaside_tiramisu', 'wolfram_ep', 'randoomplayer') then
    raise exception 'Only approved puzzle creators can publish directly';
  end if;

  if p_puzzles is null or jsonb_typeof(p_puzzles) <> 'array' then
    raise exception 'Puzzles must be supplied as an array';
  end if;

  if jsonb_array_length(p_puzzles) < 1 or jsonb_array_length(p_puzzles) > 100 then
    raise exception 'A batch must contain between 1 and 100 puzzles';
  end if;

  lock table public.puzzles in share row exclusive mode;

  select coalesce(max(id), 0) + 1
  into next_puzzle_id
  from public.puzzles;

  for item in select value from jsonb_array_elements(p_puzzles)
  loop
    normalized_fen := btrim(coalesce(item->>'fen', ''));
    normalized_solution := regexp_replace(
      btrim(coalesce(item->>'solution', '')),
      '[[:space:]]+',
      ' ',
      'g'
    );
    normalized_author := case
      when normalized_username = 'seaside_tiramisu'
        then coalesce(nullif(btrim(item->>'author'), ''), normalized_username)
      else normalized_username
    end;

    if normalized_fen = '' then
      raise exception 'A FEN is required';
    end if;

    if normalized_solution = '' then
      raise exception 'A solution is required';
    end if;

    insert into public.puzzles (
      id, fen, solution, event, event_name, event_date, players,
      white_player, black_player, explanation, opa_style, author, tags, position_moves, game_initial_fen
    )
    values (
      next_puzzle_id,
      normalized_fen,
      normalized_solution,
      btrim(coalesce(item->>'event', '')),
      btrim(coalesce(item->>'eventName', '')),
      btrim(coalesce(item->>'eventDate', '')),
      coalesce(
        array(select jsonb_array_elements_text(coalesce(item->'players', '[]'::jsonb))),
        '{}'::text[]
      ),
      btrim(coalesce(item->>'whitePlayer', '')),
      btrim(coalesce(item->>'blackPlayer', '')),
      btrim(coalesce(item->>'explanation', '')),
      coalesce((item->>'opaStyle')::boolean, false),
      normalized_author,
      coalesce(
        array(select jsonb_array_elements_text(coalesce(item->'tags', '[]'::jsonb))),
        '{}'::text[]
      ),
      item->'positionMoves',
      item->>'gameInitialFen'
    );

    puzzle_ids := array_append(puzzle_ids, next_puzzle_id);
    next_puzzle_id := next_puzzle_id + 1;
  end loop;

  select pg_get_serial_sequence('public.puzzles', 'id')
  into puzzle_id_sequence;

  if puzzle_id_sequence is not null then
    perform setval(puzzle_id_sequence::regclass, next_puzzle_id - 1, true);
  end if;

  return puzzle_ids;
end;
$$;

-- Only tournament matches reserve a canonical set. Other game puzzles keep
-- their source game, match and position history without creating a set.
-- Requires puzzle_sets.sql and puzzle_game_id.sql.
drop function if exists public.save_match_puzzle(jsonb, text, text, text, bigint, boolean, boolean);

create or replace function public.save_match_puzzle(
  p_puzzle jsonb,
  p_submitted_by text,
  p_game_id text,
  p_match_id text,
  p_legacy_set_id bigint,
  p_publish boolean,
  p_allow_different_start_move boolean default false,
  p_rename_from text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  match_set public.puzzle_sets%rowtype;
  set_name text := '';
  set_date text := coalesce(p_puzzle->>'eventDate', '');
  set_players text[] := public.normalize_puzzle_set_players(
    array(select jsonb_array_elements_text(p_puzzle->'players'))
  );
  tournament_match boolean := coalesce((p_puzzle->>'tournamentMatch')::boolean, false)
    or exists (select 1 from public.tournament_matches where match_id = p_match_id);
  saved_puzzle_id bigint;
  source_moves jsonb := p_puzzle->'positionMoves';
  source_fen text := p_puzzle->>'gameInitialFen';
  queued public.puzzles_queue%rowtype;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_match_id, 1));
  if p_rename_from is not null then
    raise exception 'Match set name changed';
  end if;

  if tournament_match then
    select * into match_set
    from public.puzzle_sets
    where source_id = p_match_id
       or (id = p_legacy_set_id and source_id is null)
    order by (source_id = p_match_id) desc nulls last, id
    limit 1;

    set_name := coalesce(match_set.event_name, nullif(btrim(p_puzzle->>'eventName'), ''));
    set_date := coalesce(match_set.event_date, set_date);
    set_players := coalesce(match_set.players, set_players);
    if set_name is null then
      raise exception 'Missing tournament set name';
    end if;
  end if;

  if p_publish then
    saved_puzzle_id := (public.publish_approved_puzzle_batch(
      jsonb_build_array(p_puzzle || jsonb_build_object(
        'event', set_name, 'eventName', set_name, 'eventDate', set_date, 'players', set_players
      )),
      p_submitted_by,
      p_allow_different_start_move
    ))[1];
    update public.puzzles
    set game_id = p_game_id, match_id = p_match_id,
        position_moves = source_moves, game_initial_fen = source_fen
    where id = saved_puzzle_id;
  else
    queued := public.enqueue_puzzle_submission(
      p_puzzle->>'fen', p_puzzle->>'solution', set_name, set_name, set_date, set_players,
      p_puzzle->>'whitePlayer', p_puzzle->>'blackPlayer', p_puzzle->>'explanation',
      coalesce((p_puzzle->>'opaStyle')::boolean, false), p_puzzle->>'author',
      array(select jsonb_array_elements_text(p_puzzle->'tags')),
      p_submitted_by, p_allow_different_start_move
    );
    update public.puzzles_queue
    set game_id = p_game_id, match_id = p_match_id,
        position_moves = source_moves, game_initial_fen = source_fen
    where id = queued.id;
  end if;

  if tournament_match then
    if match_set.id is null then
      insert into public.puzzle_sets (event_name, event_date, players)
      values (set_name, set_date, set_players) on conflict do nothing;

      select * into match_set
      from public.puzzle_sets
      where lower(btrim(event_name)) = lower(btrim(set_name))
        and event_date = set_date
        and public.normalize_puzzle_set_players(players) = set_players
      limit 1;
    end if;

    update public.puzzle_sets set source_id = p_match_id
    where id = match_set.id and (source_id is null or source_id = p_match_id);
    if not found then
      raise exception 'Puzzle set belongs to another match';
    end if;
  end if;

  if p_publish then
    return jsonb_build_object('destination', 'published', 'puzzleId', saved_puzzle_id, 'setName', set_name);
  end if;
  return jsonb_build_object('destination', 'review', 'setName', set_name);
end;
$$;

