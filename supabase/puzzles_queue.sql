-- Puzzle submission queue for Atomic Puzzles.
-- Includes the write functions used by the submission and review flows.

create table if not exists public.puzzles_queue (
  id bigint generated by default as identity primary key,
  fen text not null check (length(btrim(fen)) > 0),
  solution text not null check (length(btrim(solution)) > 0),
  event text not null default '',
  event_name text not null default '',
  event_date text not null default '',
  players text[] not null default '{}'::text[],
  white_player text not null default '',
  black_player text not null default '',
  explanation text not null default '',
  opa_style boolean not null default false,
  author text not null default '',
  tags text[] not null default '{}'::text[],
  submitted_by text not null check (length(btrim(submitted_by)) > 0),
  created_at timestamptz not null default now()
);

