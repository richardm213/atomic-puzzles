-- Submission and review access goes through server-side functions that verify
-- the caller's Lichess access token. The browser receives no direct queue
-- privileges, and the service role bypasses RLS only after verification.
drop policy if exists "public can submit pending puzzles" on public.puzzles_queue;

drop policy if exists "public can read puzzle queue" on public.puzzles_queue;
drop policy if exists "public can edit pending puzzles" on public.puzzles_queue;

revoke all on public.puzzles_queue from anon, authenticated;
revoke usage, select on sequence public.puzzles_queue_id_seq from anon, authenticated;
revoke all on function public.enqueue_puzzle_submission(text, text, text, text, text) from public;
grant execute on function public.enqueue_puzzle_submission(text, text, text, text, text) to service_role;
revoke all on function public.publish_approved_puzzle_submission(text, text, text, text, text) from public;
grant execute on function public.publish_approved_puzzle_submission(text, text, text, text, text) to service_role;
revoke all on function public.publish_approved_puzzle_batch(jsonb, text) from public;
grant execute on function public.publish_approved_puzzle_batch(jsonb, text) to service_role;
revoke all on function public.approve_queued_puzzle(bigint, text, bigint) from public;
grant execute on function public.approve_queued_puzzle(bigint, text, bigint) to service_role;

