-- Reversible puzzle deletion with a complete audit snapshot.

alter table public.puzzles
  add column if not exists deleted_at timestamptz,
  add column if not exists deleted_by text;

create index if not exists puzzles_active_id_idx
  on public.puzzles (id desc)
  where deleted_at is null;

create table if not exists public.puzzle_deletions (
  id bigint generated by default as identity primary key,
  puzzle_id bigint not null,
  puzzle_snapshot jsonb not null,
  deleted_by text not null,
  deleted_at timestamptz not null default now(),
  restored_by text,
  restored_at timestamptz
);

create index if not exists puzzle_deletions_puzzle_idx
  on public.puzzle_deletions (puzzle_id, deleted_at desc);

create or replace function public.soft_delete_puzzle(
  p_puzzle_id bigint,
  p_deleted_by text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_username text := lower(btrim(coalesce(p_deleted_by, '')));
  puzzle_row public.puzzles%rowtype;
begin
  if normalized_username <> 'seaside_tiramisu' then
    raise exception 'Only seaside_tiramisu can delete puzzles';
  end if;

  select * into puzzle_row
  from public.puzzles
  where id = p_puzzle_id
  for update;

  if not found then
    raise exception 'Puzzle % was not found', p_puzzle_id;
  end if;

  if puzzle_row.deleted_at is not null then
    raise exception 'Puzzle % is already deleted', p_puzzle_id;
  end if;

  insert into public.puzzle_deletions (
    puzzle_id,
    puzzle_snapshot,
    deleted_by
  )
  values (
    p_puzzle_id,
    to_jsonb(puzzle_row),
    normalized_username
  );

  update public.puzzles
  set deleted_at = now(), deleted_by = normalized_username
  where id = p_puzzle_id;
end;
$$;

create or replace function public.restore_deleted_puzzle(
  p_puzzle_id bigint,
  p_restored_by text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_username text := lower(btrim(coalesce(p_restored_by, '')));
  deletion_id bigint;
begin
  if normalized_username <> 'seaside_tiramisu' then
    raise exception 'Only seaside_tiramisu can restore puzzles';
  end if;

  select id into deletion_id
  from public.puzzle_deletions
  where puzzle_id = p_puzzle_id
    and restored_at is null
  order by deleted_at desc
  limit 1
  for update;

  if deletion_id is null then
    raise exception 'Deleted puzzle % was not found', p_puzzle_id;
  end if;

  update public.puzzles
  set deleted_at = null, deleted_by = null
  where id = p_puzzle_id
    and deleted_at is not null;

  if not found then
    raise exception 'Puzzle % is not deleted', p_puzzle_id;
  end if;

  update public.puzzle_deletions
  set restored_at = now(), restored_by = normalized_username
  where id = deletion_id;
end;
$$;

alter table public.puzzle_deletions enable row level security;
revoke all on public.puzzle_deletions from public, anon, authenticated;
revoke usage, select on sequence public.puzzle_deletions_id_seq from public, anon, authenticated;

revoke all on function public.soft_delete_puzzle(bigint, text) from public;
grant execute on function public.soft_delete_puzzle(bigint, text) to service_role;
revoke all on function public.restore_deleted_puzzle(bigint, text) from public;
grant execute on function public.restore_deleted_puzzle(bigint, text) to service_role;

notify pgrst, 'reload schema';
