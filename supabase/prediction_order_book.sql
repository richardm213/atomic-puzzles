-- Keep traded volume on the market row so catalog and strike-list reads do not
-- have to scan and sum the fills table. The backfill makes this migration safe
-- for existing markets; the trigger maintains the value for later fill changes.
update public.prediction_markets market
set exchange_volume_coins = coalesce((
  select sum(fill.price_cents::numeric * fill.quantity::numeric / 100)
  from public.prediction_fills fill
  where fill.market_id = market.id
), 0);

create or replace function public.adjust_prediction_market_exchange_volume()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op in ('DELETE', 'UPDATE') then
    update public.prediction_markets
    set exchange_volume_coins = greatest(
      0,
      exchange_volume_coins - (old.price_cents::numeric * old.quantity::numeric / 100)
    )
    where id = old.market_id;
  end if;

  if tg_op in ('INSERT', 'UPDATE') then
    update public.prediction_markets
    set exchange_volume_coins =
      exchange_volume_coins + (new.price_cents::numeric * new.quantity::numeric / 100)
    where id = new.market_id;
  end if;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function public.adjust_prediction_market_exchange_volume() from public;

drop trigger if exists prediction_fills_adjust_volume on public.prediction_fills;
create trigger prediction_fills_adjust_volume
after insert or update of market_id, price_cents, quantity or delete on public.prediction_fills
for each row execute function public.adjust_prediction_market_exchange_volume();

