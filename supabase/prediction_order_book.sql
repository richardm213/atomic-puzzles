-- Coin-backed binary prediction markets with price-time matching.
begin;

create table if not exists public.prediction_markets (
  id text primary key,
  question text not null,
  resolution_rules text not null,
  resolution_source_url text not null,
  closes_at timestamptz not null,
  status text not null default 'open' check (status in ('open', 'closed', 'resolved', 'refunded')),
  outcome text check (outcome in ('yes', 'no')),
  settlement_price_cents integer check (settlement_price_cents between 0 and 100),
  settlement_reference_fill_id bigint,
  sportsbook_volume_coins numeric(18, 6) not null default 0 check (sportsbook_volume_coins >= 0),
  exchange_volume_coins numeric(18, 6) not null default 0 check (exchange_volume_coins >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz,
  constraint prediction_markets_resolution_check check (
    (status = 'resolved' and ((outcome is not null)::integer +
      (settlement_price_cents is not null)::integer) = 1)
    or
    (status <> 'resolved' and outcome is null and settlement_price_cents is null)
  ),
  constraint prediction_markets_settlement_reference_check
    check ((settlement_price_cents is null) = (settlement_reference_fill_id is null))
);

create table if not exists public.prediction_orders (
  id bigint generated by default as identity primary key,
  market_id text not null references public.prediction_markets(id),
  username text not null,
  outcome text not null check (outcome in ('yes', 'no')),
  side text not null check (side in ('buy', 'sell')),
  price_cents integer not null check (price_cents between 1 and 99),
  quantity integer not null check (quantity > 0),
  filled_quantity integer not null default 0 check (filled_quantity >= 0),
  remaining_quantity integer not null check (remaining_quantity >= 0),
  status text not null default 'open' check (status in ('open', 'partial', 'filled', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (filled_quantity + remaining_quantity <= quantity)
);

create index if not exists prediction_orders_book_idx
  on public.prediction_orders (market_id, outcome, side, status, price_cents, created_at, id);
create index if not exists prediction_orders_user_idx
  on public.prediction_orders (username, market_id, created_at desc);

create table if not exists public.prediction_positions (
  market_id text not null references public.prediction_markets(id),
  username text not null,
  outcome text not null check (outcome in ('yes', 'no')),
  quantity numeric(18, 6) not null default 0 check (quantity >= 0),
  reserved_quantity numeric(18, 6) not null default 0 check (reserved_quantity >= 0),
  updated_at timestamptz not null default now(),
  primary key (market_id, username, outcome),
  check (reserved_quantity <= quantity)
);

create table if not exists public.prediction_legacy_position_credits (
  source_bet_id bigint primary key references public.tournament_bets(id),
  market_id text not null references public.prediction_markets(id),
