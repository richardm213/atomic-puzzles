-- One prediction position model. Historical fixed-price records remain read-only
-- archives so old financial receipts and earlier deployments stay auditable.
begin;
create table if not exists public.prediction_position_credits (
 id bigint generated by default as identity primary key,
 source_key text not null unique,
 market_id text not null references public.prediction_markets(id),
 username text not null check(username=lower(btrim(username))),
 outcome text not null check(outcome in('yes','no')),
 quantity numeric(18,6) not null check(quantity>0),
 price_cents integer not null check(price_cents between 1 and 99),
 cost_coins numeric(18,6) not null check(cost_coins>0),
 fee_coins numeric(18,6) not null default 0 check(fee_coins>=0),
 credited_at timestamptz not null,
 metadata jsonb not null default '{}'
);
create index if not exists prediction_position_credits_owner on public.prediction_position_credits(market_id,username);
alter table public.prediction_position_credits enable row level security;
revoke all on public.prediction_position_credits from public,anon,authenticated;
grant select on public.prediction_position_credits to service_role;
create table if not exists public.prediction_migration_snapshots (
 migration_key text primary key, snapshot jsonb not null, created_at timestamptz not null default now()
);
alter table public.prediction_migration_snapshots enable row level security;
revoke all on public.prediction_migration_snapshots from public,anon,authenticated;
grant select on public.prediction_migration_snapshots to service_role;

do $$
declare migration text:='canonical-predictions-20261116-v1'; original_wallets jsonb; current_wallets jsonb;
begin
 if exists(select 1 from public.prediction_migration_snapshots where migration_key=migration) then return; end if;
 lock table public.tournament_bets,public.tournament_betting_markets,public.tournament_betting_outcomes,public.prediction_legacy_position_credits in share row exclusive mode;
 lock table public.coin_accounts in share row exclusive mode;
 if exists(select 1 from public.tournament_bets b where not exists(select 1 from public.prediction_legacy_position_credits c where c.source_bet_id=b.id))
 then raise exception 'Unconverted fixed-price bet remains; map it before migrating'; end if;
 if exists(select 1 from public.tournament_bets b
  join public.prediction_legacy_position_credits c on c.source_bet_id=b.id
  join public.prediction_markets m on m.id=c.market_id
  join public.tournament_betting_markets old on old.id=b.market_id
  where c.quantity<>b.potential_payout or c.price_cents<>b.price_cents or c.username<>b.username
   or c.outcome<>case when old.market_kind='match' then case when lower(m.outcome_yes_label)=b.selection then 'yes' else 'no' end
     else case when b.market_id like '%-no' then 'no' else 'yes' end end
   or (b.status='open' and m.status not in('open','closed')))
 then raise exception 'Source bet does not match its prediction strike'; end if;
 -- All earlier payouts have already been reconciled into prediction receipts.
 if exists(select 1 from public.coin_transactions where reason='tournament_bet_payout') then raise exception 'Unmigrated sportsbook payout remains'; end if;
 select jsonb_agg(to_jsonb(a) order by a.username) into original_wallets from public.coin_accounts a;
 insert into public.prediction_migration_snapshots(migration_key,snapshot) values(migration,jsonb_build_object(
  'wallets',original_wallets,
  'bets',(select jsonb_agg(to_jsonb(b) order by id) from public.tournament_bets b),
  'markets',(select jsonb_agg(to_jsonb(m) order by id) from public.tournament_betting_markets m),
  'outcomes',(select jsonb_agg(to_jsonb(o)) from public.tournament_betting_outcomes o),
  'credits',(select jsonb_agg(to_jsonb(c) order by source_bet_id) from public.prediction_legacy_position_credits c),
  'receipts',(select jsonb_agg(to_jsonb(t) order by id) from public.coin_transactions t where reason like 'tournament_bet%')
 ));
 insert into public.prediction_position_credits(id,source_key,market_id,username,outcome,quantity,price_cents,cost_coins,fee_coins,credited_at,metadata)
 select c.source_bet_id,'imported-position:'||c.source_bet_id,c.market_id,c.username,c.outcome,c.quantity,c.price_cents,b.total_cost,b.fee,b.placed_at,
  jsonb_build_object('importedFrom','fixed-price-bet','originalBetId',b.id,'originalMarketId',b.market_id,'importedAt',c.credited_at)
 from public.prediction_legacy_position_credits c join public.tournament_bets b on b.id=c.source_bet_id;
 perform setval(pg_get_serial_sequence('public.prediction_position_credits','id'),greatest(1,(select max(id) from public.prediction_position_credits)),true);
 -- Preserve the exact amount, ID and time of each purchase. Its canonical market
 -- and credit ID make history independent of the old sportsbook tables.
 update public.coin_transactions t set metadata=t.metadata||jsonb_build_object('marketId',c.market_id,'outcome',c.outcome,'positionCreditId',c.id,'chargeMode','fill',
   'quantity',case when nullif(t.metadata->>'stake','') is not null and nullif(t.metadata->>'priceCents','') is not null
    then (t.metadata->>'stake')::numeric*100/(t.metadata->>'priceCents')::numeric else c.quantity end)
 from public.prediction_position_credits c where t.reason='tournament_bet' and t.metadata->>'betId'=c.id::text;
 select jsonb_agg(to_jsonb(a) order by a.username) into current_wallets from public.coin_accounts a;
 if current_wallets is distinct from original_wallets then raise exception 'Migration changed a wallet'; end if;
 if (select count(*) from public.prediction_position_credits)<>(select count(*) from public.prediction_legacy_position_credits)
 then raise exception 'Position import incomplete'; end if;
end;
$$;

-- Archives cannot create a second entitlement or silently accept old clients.
create or replace function public.reject_retired_sportsbook_write()
returns trigger language plpgsql set search_path='' as $$
begin raise exception 'Fixed-price bets are retired; use prediction market orders'; end;
$$;
do $$
declare t text; trigger_row record;
begin
 for trigger_row in select tgrelid::regclass relation,tgname from pg_trigger where not tgisinternal and tgfoid=to_regprocedure('public.settle_awc2026_betting_market_from_bracket()') loop
  execute format('drop trigger %I on %s',trigger_row.tgname,trigger_row.relation);
 end loop;
 foreach t in array array['tournament_bets','tournament_betting_markets','tournament_betting_outcomes','prediction_legacy_position_credits'] loop
  execute format('alter table public.%I enable row level security',t);
  execute format('revoke all on public.%I from public,anon,authenticated',t);
  execute format('revoke insert,update,delete,truncate on public.%I from service_role',t);
  execute format('grant select on public.%I to service_role',t);
  execute format('drop trigger if exists reject_retired_sportsbook_write on public.%I',t);
  execute format('create trigger reject_retired_sportsbook_write before insert or update or delete on public.%I for each statement execute function public.reject_retired_sportsbook_write()',t);
  execute format('comment on table public.%I is %L',t,'Read-only historical archive. Active betting uses prediction markets and prediction_position_credits.');
 end loop;
end;
$$;
